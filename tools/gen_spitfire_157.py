#!/usr/bin/env python3
"""157 versions of SPS Equipment's four Vortex Spitfire Gen II 5x (user, 2026-10-17):

    "make 157 versions of the 4 sps spitfires, where the 4.5 has the ace 157 system and the red dot on them does not"

    sps_vortex_spitfire_gen2_x5_black       sps_vortex_spitfire_gen2_x5_RMR_black
    sps_vortex_spitfire_gen2_x5_tan         sps_vortex_spitfire_gen2_x5_RMR_tan

Each JMSB version (jmfsb_optics_<source>_157) is the Spitfire - its model, picture, rail and look, inherited - with
ACE's XM157 fire-control on the magnified sight (their 4.5x - a zoom of 0.055), built the way ACE builds its own prototype (ace_xm157 CfgWeapons):

  * weaponInfoType = "ace_xm157_info" and a CBA_ScriptedOptic block - the XM157 display
  * ItemInfo.modelOptics = CBA's scripted-optic model; the magnified mode useModelOptics = 1 with its zoom held at
    the Spitfire's own magnification through CBA's magnification helper
  * the RMR red dot (useModelOptics = 0) left as the Spitfire has it - CBA draws no scripted overlay there, so the
    red dot has no XM157

The Spitfires live in an OBFUSCATED PBO (sps_vortex_spitfire_gen2), which nothing outside the game should unpack,
so the source is the in-game dump: tools/dump_optics.sqf (its "spitfire" pattern) -> tools/_dump/optics.txt. The
sight block is written out whole from what the game resolved - every value the Spitfire's modes have, inherited or
not - so nothing here re-parents a class of theirs: only the Spitfire itself and InventoryOpticsItem_Base_F are
named as parents.

The goggles see through both sights (visionMode[] = {}), as through every JMSB scope (compatibility/nvg_optics_*).

    python tools/gen_spitfire_157.py      -> addons/compatibility/xm157_spitfire
"""
import collections
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DUMP = os.path.join(ROOT, "tools", "_dump", "game_optics.txt")      # tools/dump_optics.sqf, from the RPT
OUT = os.path.join(ROOT, "addons", "compatibility", "xm157_spitfire")
HEADER = "// Generated by tools/gen_spitfire_157.py - re-run rather than hand-edit.\n"
SOURCES = [
    "sps_vortex_spitfire_gen2_x5_black", "sps_vortex_spitfire_gen2_x5_tan",
    "sps_vortex_spitfire_gen2_x5_RMR_black", "sps_vortex_spitfire_gen2_x5_RMR_tan",
]
CBA_MODEL = "\\x\\cba\\addons\\optics\\cba_optic_big_100.p3d"
# the engine's 1x is a zoom of 0.25: the Spitfire's 0.055 is its 4.5x, and CBA's helper takes the magnification
BASE_ZOOM = 0.25
ZOOM = "%g call (uiNamespace getVariable 'cba_optics_fnc_setOpticMagnificationHelper')"
SCRIPTED_OPTIC = [
    'bodyTexture = "\\z\\ace\\addons\\xm157\\data\\ace_vector_body_co.paa";',
    "bodyTextureSize = 1;",
    "hideMagnification = 1;",
    "disableTilt = 0;",
]


def mag_set(magnification):
    """What the magnified mode is given on top of its own values."""
    zoom = '"%s"' % (ZOOM % magnification)
    return {"useModelOptics": "1", "modelOptics": '"%s"' % CBA_MODEL,
            "opticsZoomMin": zoom, "opticsZoomMax": zoom, "opticsZoomInit": zoom, "visionMode[]": "{}"}


DROP = {"discretefov", "discreteinitindex"}            # CBA's helper owns the zoom; a fixed FOV list fights it


def to_config(text):
    """An SQF str value as config text: "x" stays, [..] becomes {..}, numbers as they are."""
    text = text.strip()
    if text.startswith("["):
        return "{" + to_config_list(text[1:-1]) + "}"
    return text


def to_config_list(body):
    out, depth, cur, quote = [], 0, "", False
    for ch in body:
        if ch == '"':
            quote = not quote
        if not quote and ch == "[":
            depth += 1
        if not quote and ch == "]":
            depth -= 1
        if not quote and ch == "," and depth == 0:
            out.append(to_config(cur))
            cur = ""
            continue
        cur += ch
    if cur.strip():
        out.append(to_config(cur))
    return ", ".join(out)


def load(path):
    classes, values = {}, collections.defaultdict(collections.OrderedDict)
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.rstrip("\n")
        if line.startswith("OPTICS;"):
            line = line[len("OPTICS;"):]
        if line.startswith("CLS;"):
            _, path_, parent, own = line.split(";", 3)
            classes[path_] = (parent, own == "1")
        elif line.startswith("VAL;"):
            _, path_, name, own, value = line.split(";", 4)
            values[path_][name] = value
    return classes, values


def prop(name, value):
    value = to_config(value)
    return "%s[] = %s;" % (name, value) if value.startswith("{") else "%s = %s;" % (name, value)


def main():
    if not os.path.isfile(DUMP):
        sys.exit("no %s - run tools/dump_optics.sqf in the game and put its OPTICS; lines there" % DUMP)
    classes, values = load(DUMP)
    missing = [s for s in SOURCES if "CfgWeapons/" + s not in classes]
    if missing:
        sys.exit("the dump has no %s - was it made with SPS Equipment loaded?" % ", ".join(missing))

    blocks, weapons = [], []
    for src in SOURCES:
        base = "CfgWeapons/" + src
        modes_path = base + "/ItemInfo/OpticsModes"
        modes = [p for p in classes if p.startswith(modes_path + "/") and p.count("/") == modes_path.count("/") + 1]
        if not modes:
            sys.exit("%s has no OpticsModes in the dump" % src)
        # the magnified sight: the one drawn through the optic model (useModelOptics 1); the rest are the red dot
        mag = [m for m in modes if values[m].get("useModelOptics", "0").strip() == "1"]
        if len(mag) != 1:
            sys.exit("%s: expected one magnified mode, found %s" % (src, [m.rsplit("/", 1)[1] for m in mag]))
        mag = mag[0]
        magnification = round(BASE_ZOOM / float(values[mag]["opticsZoomInit"]), 1)
        print("%s: %s at %gx" % (src, mag.rsplit("/", 1)[1], magnification))
        display = values[base].get("displayName", '"%s"' % src).strip('"')
        cls = "jmfsb_optics_%s_157" % src
        weapons.append(cls)

        lines = ["    class %s: %s {" % (cls, src),
                 "        author = QAUTHOR;",
                 "        scope = 2;",
                 "        scopeArsenal = 2;",
                 '        displayName = "[JMSB] %s (XM157)";' % display,
                 '        weaponInfoType = "ace_xm157_info";',
                 "        class CBA_ScriptedOptic {"]
        lines += ["            " + s for s in SCRIPTED_OPTIC]
        lines += ["        };",
                  "        class ItemInfo: InventoryOpticsItem_Base_F {"]
        for name, value in values[base + "/ItemInfo"].items():
            if name.lower() in ("modeloptics", "weaponinfotype"):
                continue
            lines.append("            " + prop(name, value))
        lines += ['            modelOptics = "%s";' % CBA_MODEL,
                  '            weaponInfoType = "ace_xm157_info";',
                  "            class OpticsModes {"]
        # THE XM157 SIGHT FIRST, as opticsID 1. CBA restores a scripted optic's magnification by taking the optic off
        # the weapon and putting it back (cba_optics_fnc_setOpticMagnification, on entering the sight), and a
        # re-added optic starts on its first mode: with the red dot first, switching to the 157 blinked and dropped
        # back to the red dot (user, 2026-10-17). ACE's own XM157 has one mode, so it never shows.
        ordered = [mag] + [m for m in modes if m != mag]
        for index, mode in enumerate(ordered, 1):
            name = mode.rsplit("/", 1)[1]
            lines.append("                class %s {" % name)
            given = dict(mag_set(magnification) if mode == mag else {"visionMode[]": "{}"}, opticsID=str(index))
            for key, value in values[mode].items():
                if key.lower() in {k.lower().rstrip("[]") for k in given} or (mode == mag and key.lower() in DROP):
                    continue
                lines.append("                    " + prop(key, value))
            for key, value in given.items():
                lines.append("                    %s = %s;" % (key, value))
            lines.append("                };")
        lines += ["            };", "        };", "    };"]
        blocks.append("\n".join(lines))

    patches = sorted({p for s in SOURCES for l in open(DUMP, encoding="utf-8", errors="replace")
                      if l.startswith(("CLASS;%s;" % s, "OPTICS;CLASS;%s;" % s))
                      for p in l.rstrip("\n").split(";")[-1].split("|") if p})
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    with open(os.path.join(OUT, "script_component.hpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "#define SUBCOMPONENT xm157_spitfire\n#include \"..\\script_component.hpp\"\n")
    with open(os.path.join(OUT, "config.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + """#include "script_component.hpp"

// THE 157 SPITFIRES (user, 2026-10-17) - SPS Equipment's Vortex Spitfire Gen II with ACE's XM157 fire-control on
// the 4.5x sight, the RMR red dot left plain. See tools/gen_spitfire_157.py.
class CfgPatches {
    class SUBADDON {
        name = COMPONENT_NAME;
        units[] = {};
        weapons[] = {
%s
        };
        requiredVersion = REQUIRED_VERSION;
        requiredAddons[] = {
            "jmfsb_main",
            "ace_xm157",
            "cba_optics",
            "cba_jr",
%s
        };
        skipWhenMissingDependencies = 1;
        author = QAUTHOR;
        VERSION_CONFIG;
    };
};

// ON THE RAIL. A scope only mounts where its class is listed: CBA's joint rails list them by name, and SPS lists
// its Spitfires there - these are new names, so they are listed too (2026-10-17 RPT, before they were: "item[...157]
// does not match to this weapon!" on the HK416).
class asdg_OpticRail;
class asdg_OpticRail1913: asdg_OpticRail {
    class compatibleItems {
%s
    };
};

#include "CfgWeapons.hpp"
""" % (",\n".join('            "%s"' % w for w in weapons),
       ",\n".join('            "%s"' % p for p in patches) or '            "sps_vortex_spitfire_gen2"',
       "\n".join("        %s = 1;" % w for w in weapons)))
    with open(os.path.join(OUT, "CfgWeapons.hpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + "class CfgWeapons {\n    class InventoryOpticsItem_Base_F;\n")
        for s in SOURCES:
            f.write("    class %s;\n" % s)
        f.write("\n".join(blocks) + "\n};\n")
    for w in weapons:
        print(w)


if __name__ == "__main__":
    main()
