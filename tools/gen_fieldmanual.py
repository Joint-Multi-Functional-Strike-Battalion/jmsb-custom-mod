#!/usr/bin/env python3
"""The unit's how-to in Arma's Field Manual (user, 2026-10-23: "there is a
field manual in arma can we put all our how to data in there").

The sign boards ARE the how-to, and tools/gen_signs.py holds their words as
data (SIGNS / FA_SIGNS). This writes the same words as CfgHints entries -
one category, a topic per group, an entry per board with the board itself as
the picture - so the manual and the signs cannot drift apart. Wayfinding
boards (titles only), uniform swatches and duplicates are left out.

    python tools/gen_fieldmanual.py

Writes addons/fieldmanual/CfgHints.hpp (generated; never hand-edit).
"""
import os
import re

import gen_signs

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "addons", "fieldmanual", "CfgHints.hpp"))
IMAGE = r"\z\jmfsb\addons\media\images\signs_v2_plain\%s.paa"
FA_IMAGE = r"\z\jmfsb\addons\fa_main\data\%s.paa"

CATEGORY = ("JMSB", "1st JMSB")
# Topic class, title, the boards in it (gen_signs.SIGNS keys; fa_ keys from FA_SIGNS).
TOPICS = [
    ("RadioVoice", "Radio voice", ["radio_howto", "radio_nets", "radio_keys"]),
    ("Radios", "Radios", ["radio_sets"]),
    ("Devices", "Devices", ["radio_phone", "radio_side", "simple_phone", "simple_side"]),
    ("Tablets", "Tablets", ["radio_tablet", "tablet_apps", "simple_tablet"]),
    ("Staging", "Staging zone", ["access", "jmfsbroles", "jmfsbbtime", "jmfsbcallsign", "keybinds", "good2know", "viewd", "bodies", "gtk", "patrol_base"]),
    ("MapTablet", "Map and tablet", ["tacpad", "ctab", "markers", "marker_range"]),
    ("Ammunition", "Ammunition", ["fa_sign_40mm", "fa_sign_65_mx", "fa_sign_jca_556", "fa_sign_jca_762", "fa_sign_nato_rockets"]),
]
# The boards' own palette, as structured text colours.
TAN = "#C2A878"
SAGE = "#A9AE95"
BONE = "#E9E4D3"


def esc(s):
    """A config string's inside: doubled quotes, and an ampersand the
    structured text parser will not choke on."""
    return str(s).replace("&", "&amp;").replace('"', '""')


def des(d):
    return "<t color='%s'>%s</t>" % (TAN, esc(d))


def rows(items):
    out = []
    for item in items:
        d, text = (list(item) + [""])[:2]
        out.append(des(d) + (" - " + esc(text) if text else ""))
    return "<br/>".join(out)


def body(spec):
    """The entry's text from a board spec, by kind."""
    kind = spec["kind"]
    parts = []
    if spec.get("sub"):
        parts.append("<t color='%s'>%s</t>" % (SAGE, esc(spec["sub"])))
    if kind == "rows":
        parts.append(rows(spec["items"]))
    elif kind == "keys":
        for heading, items in spec["columns"]:
            parts.append("<t color='%s'>%s</t><br/>" % (TAN, esc(heading.upper())) + "<br/>".join(
                "%s: <t color='%s'>%s</t>" % (esc(label), BONE, esc(key.lstrip("!"))) for label, key in items))
    elif kind == "sections":
        for heading, note, items in spec["blocks"]:
            head = "<t color='%s'>%s</t>" % (TAN, esc(heading.upper()))
            if note:
                head += " <t color='%s'>%s</t>" % (SAGE, esc(note))
            parts.append(head + "<br/>" + rows(items))
    elif kind == "devices":
        parts.append("<br/>".join("<t color='%s'>%s</t>  %s" % (TAN, i + 1, esc(line)) for i, line in enumerate(spec["key"])))
    elif kind == "ammo2":
        for heading, items in spec["columns"]:
            parts.append("<t color='%s'>%s</t><br/>" % (TAN, esc(heading.upper())) + rows(items))
    else:
        raise SystemExit("no manual text for a %r board" % kind)
    if spec.get("foot"):
        parts.append("<t color='%s'>%s</t>" % (SAGE, esc(spec["foot"])))
    return "<br/><br/>".join(parts)


def tip(spec):
    """The one line the game shows as the hint itself."""
    return esc(spec.get("sub") or spec.get("foot") or spec["title"])


def class_name(name):
    return "".join(w.capitalize() for w in re.split(r"[^a-z0-9]+", name.lower()) if w)


def main():
    boards = dict(gen_signs.SIGNS)
    boards.update(gen_signs.FA_SIGNS)
    lines = [
        "// GENERATED by tools/gen_fieldmanual.py from tools/gen_signs.py - do not edit.",
        "// The unit's how-to in the Field Manual: the sign boards' words, the boards as the pictures.",
        "class CfgHints {",
        "    class %s {" % CATEGORY[0],
        '        displayName = "%s";' % CATEGORY[1],
    ]
    count = 0
    for topic, title, names in TOPICS:
        lines.append("        class %s {" % topic)
        lines.append('            displayName = "%s";' % esc(title))
        for name in names:
            spec = boards[name]
            image = (FA_IMAGE if name.startswith("fa_sign_") else IMAGE) % name
            lines.append("            class %s {" % class_name(name))
            lines.append('                displayName = "%s";' % esc(spec["title"]))
            lines.append('                description = "%s";' % body(spec))
            lines.append('                tip = "%s";' % tip(spec))
            lines.append("                arguments[] = {};")
            lines.append('                image = "%s";' % image)
            lines.append("            };")
            count += 1
        lines.append("        };")
    lines += ["    };", "};", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("%d entries in %d topics -> %s" % (count, len(TOPICS), os.path.relpath(OUT)))


if __name__ == "__main__":
    main()
