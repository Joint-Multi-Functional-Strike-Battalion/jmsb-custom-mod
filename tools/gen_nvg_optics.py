#!/usr/bin/env python3
"""Every scope NVG-compatible (user, 2026-10-17: "make all scopes in the arsenal nvg compatable").

A scope whose OpticsModes name their own visionMode[] switches the goggle off the moment the player looks through
it, and even one that lists "NVG" opens in its first mode, Normal (user, 2026-10-17: "when you have nvgs on the
scope nvg should also be on, or set it so the nvgs can see through the scope"). A mode that names NO visionMode
is seen through with whatever the goggle is doing - the way a red dot is. So, per source mod, a compat sub-addon:

    addons/compatibility/nvg_optics_<mod>/      skipWhenMissingDependencies = 1

  * a mode without thermal gets visionMode[] = {} - the goggles see through it: NVG on, NVG in the scope
  * a thermal mode keeps its own modes, with "NVG" put in after "Normal" (TI stays last)
A mode that names no visionMode at all already passes the goggle through, and is left alone. CBA's scripted
picture-in-picture scopes are the other half - jmfsb_nvg's FUNC(syncPipVision) puts their PiP view in the
goggle's mode.

WHERE THE CLASSES COME FROM. A patch has to restate every class on the way down - the optic, its ItemInfo, its
OpticsModes, the mode - each with exactly the parent it was written with, or it re-parents them. Mod and DLC
configs are binarized or encrypted, so the source is the game itself: tools/dump_optics.sqf, run in the debug
console with the modset loaded, writes every optic's tree to the RPT and the clipboard.

    python tools/gen_nvg_optics.py                 reads tools/_dump/optics.txt (the clipboard, pasted)
    python tools/gen_nvg_optics.py --rpt <file>    reads the OPTICS; lines out of an .rpt

Each mod's sub-addon requires every CfgPatches that touched a class it restates, so it loads after them and skips
itself when that mod is not in the load order. Re-dumping after these patches are in is safe: a mode whose NVG
came from here stays patched.
"""
import argparse
import collections
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPAT = os.path.join(ROOT, "addons", "compatibility")
DUMP = os.path.join(ROOT, "tools", "_dump", "optics.txt")
PREFIX = "nvg_optics_"
OUR_PATCH = re.compile(r"(?i)^jmfsb_compatibility_" + PREFIX)
HEADER = "// Generated by tools/gen_nvg_optics.py - re-run rather than hand-edit.\n"


def read_lines(path, rpt):
    text = open(path, encoding="utf-8", errors="replace").read()
    out = []
    for line in text.splitlines():
        if rpt:
            i = line.find("OPTICS;")
            if i < 0:
                continue
            line = line[i + len("OPTICS;"):]
        line = line.strip().strip('"')
        if line.startswith(("CLASS;", "NEST;")):
            out.append(line)
    return out


def parse(lines):
    classes, nests = {}, {}
    for line in lines:
        f = line.split(";")
        if f[0] == "CLASS":
            name, parent, mod, patches = (f + [""] * 5)[1:5]
            classes[name] = {"parent": parent, "mod": mod,
                             "patches": [p for p in patches.split("|") if p and not OUR_PATCH.match(p)],
                             "ours": any(OUR_PATCH.match(p) for p in patches.split("|"))}
        elif f[0] == "NEST":
            owner, path, parent = f[1], f[2], f[3]
            own_vm = f[4] == "1" if len(f) > 4 else False
            vm = [v for v in f[5].split("|") if v] if len(f) > 5 else []
            nests[(owner, path)] = {"parent": parent, "own_vm": own_vm, "vm": vm}
    return classes, nests


def with_nvg(vm):
    if any(v.lower() == "nvg" for v in vm):
        return list(vm)
    out = list(vm)
    i = next((k + 1 for k, v in enumerate(out) if v.lower() == "normal"), 0)
    out.insert(i, "NVG")
    return out


class Node:
    def __init__(self, name, base=None, forward=False):
        self.name, self.base, self.forward = name, base, forward
        self.kids = collections.OrderedDict()
        self.props = []


class Tree:
    """One sub-addon's CfgWeapons: the root classes it restates, each with only the nested classes it needs."""

    def __init__(self, classes, nests):
        self.classes, self.nests = classes, nests
        self.roots = collections.OrderedDict()
        self.root_forwards = set()
        self.touched = set()

    def root(self, cls):
        if cls not in self.roots:
            parent = self.classes.get(cls, {}).get("parent", "")
            if parent:
                self.root_forwards.add(parent)
                self.touched.add(parent)
            self.roots[cls] = Node(cls, parent or None)
            self.touched.add(cls)
        return self.roots[cls]

    def open(self, cls, parts):
        """The node at cls/parts, every level opened with the parent it was written with."""
        node = self.root(cls)
        for i, name in enumerate(parts):
            sub = "/".join(parts[:i + 1])
            local = self.nests.get((cls, sub))
            if local is not None:
                base = local["parent"] or None
            else:
                base = name                                  # inherited: a local copy of the parent's own
            if base == name:
                parent = self.classes.get(cls, {}).get("parent", "")
                if not parent:
                    sys.exit("%s/%s inherits %s but %s has no parent in the dump" % (cls, sub, name, cls))
                self.forward(parent, parts[:i + 1])
            elif base and i == 0:
                self.root_forwards.add(base)                 # ItemInfo: InventoryOpticsItem_Base_F
            elif base:
                if base not in node.kids:                    # a sibling: class B: A
                    node.kids[base] = Node(base, forward=True)
            kid = node.kids.get(name)
            if kid is None:
                kid = node.kids[name] = Node(name, base)
            elif kid.forward:
                kid.forward, kid.base = False, base
            node = kid
        return node

    def forward(self, cls, parts):
        node = self.open(cls, parts[:-1]) if len(parts) > 1 else self.root(cls)
        if parts[-1] not in node.kids:
            node.kids[parts[-1]] = Node(parts[-1], forward=True)

    def depth(self, cls):
        d, seen = 0, set()
        while cls in self.classes and self.classes[cls]["parent"] and cls not in seen:
            seen.add(cls)
            cls = self.classes[cls]["parent"]
            d += 1
        return d

    def render(self):
        out = ["class CfgWeapons {"]
        for name in sorted(self.root_forwards - set(self.roots), key=str.lower):
            out.append("    class %s;" % name)
        for name in sorted(self.roots, key=lambda c: (self.depth(c), c.lower())):
            self._node(self.roots[name], 1, out)
        out.append("};")
        return "\n".join(out) + "\n"

    def _node(self, node, level, out):
        pad = "    " * level
        if node.forward:
            out.append("%sclass %s;" % (pad, node.name))
            return
        out.append("%sclass %s%s {" % (pad, node.name, ": %s" % node.base if node.base else ""))
        for prop in node.props:
            out.append(pad + "    " + prop)
        kids = list(node.kids.values())
        for kid in [k for k in kids if k.forward] + [k for k in kids if not k.forward]:
            self._node(kid, level + 1, out)
        out.append("%s};" % pad)


def slug(mod):
    s = re.sub(r"[^a-z0-9]+", "_", (mod or "").lower().lstrip("@")).strip("_")
    return s or "base"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rpt", help="an .rpt holding the OPTICS; lines")
    ap.add_argument("--dump", default=DUMP, help="the clipboard, pasted (default tools/_dump/optics.txt)")
    a = ap.parse_args()
    path = a.rpt or a.dump
    if not os.path.isfile(path):
        sys.exit("no dump at %s - run tools/dump_optics.sqf in the game first (see its header)" % path)
    classes, nests = parse(read_lines(path, bool(a.rpt)))
    if not classes:
        sys.exit("no CLASS lines in %s" % path)

    trees, targets = {}, collections.Counter()
    for (owner, sub), n in sorted(nests.items()):
        parts = sub.split("/")
        if len(parts) != 3 or not n["own_vm"]:
            continue
        ours = classes.get(owner, {}).get("ours")
        thermal = any(v.lower() == "ti" for v in n["vm"])
        if thermal:
            new = with_nvg(n["vm"])
            if new == n["vm"] and not ours:
                continue                                     # NVG by its own author - nothing to do
        else:
            new = []                                         # the goggles see through it
        if not n["vm"] and not ours:
            continue
        group = slug(classes.get(owner, {}).get("mod", ""))
        tree = trees.setdefault(group, Tree(classes, nests))
        node = tree.open(owner, parts)
        node.props = ["visionMode[] = {%s};" % ", ".join('"%s"' % v for v in new)]
        targets[group] += 1

    if not trees:
        # a dump of a game that already has these patches loaded reads every scope as patched - never let that
        # wipe them (2026-10-17: it did, once)
        sys.exit("every scope in the dump already passes the goggle through - nothing written, the existing "
                 "nvg_optics_* left as they are. A dump made WITH these patches loaded cannot rebuild them: use "
                 "tools/optics_from_pbos.py.")

    # rewritten whole each run: the old sub-addons go first
    for d in os.listdir(COMPAT):
        if d.startswith(PREFIX) and os.path.isdir(os.path.join(COMPAT, d)):
            shutil.rmtree(os.path.join(COMPAT, d))

    for group, tree in sorted(trees.items()):
        sub = PREFIX + group
        d = os.path.join(COMPAT, sub)
        os.makedirs(d)
        # a class restated here loads after every patch that wrote it, so this one is last; a parent that is only
        # declared needs just the patch that first defined it
        opened = set(tree.roots)
        patches = {p for c in opened for p in classes.get(c, {}).get("patches", [])}
        patches |= {classes[c]["patches"][0] for c in tree.touched - opened if classes.get(c, {}).get("patches")}
        patches = sorted(patches, key=str.lower)
        required = ",\n".join('            "%s"' % p for p in ["jmfsb_main"] + patches)
        with open(os.path.join(d, "script_component.hpp"), "w", encoding="utf-8", newline="\n") as f:
            f.write(HEADER + "#define SUBCOMPONENT %s\n#include \"..\\script_component.hpp\"\n" % sub)
        with open(os.path.join(d, "config.cpp"), "w", encoding="utf-8", newline="\n") as f:
            f.write(HEADER + """#include "script_component.hpp"

// EVERY SCOPE KEEPS THE GOGGLE (user, 2026-10-17) - the goggles see through each OpticsModes mode that named its
// own visionMode[] (thermal ones keep theirs, with NVG added), for the scopes %s ships. See tools/gen_nvg_optics.py.
class CfgPatches {
    class SUBADDON {
        name = COMPONENT_NAME;
        units[] = {};
        weapons[] = {};
        requiredVersion = REQUIRED_VERSION;
        requiredAddons[] = {
%s
        };
        skipWhenMissingDependencies = 1;
        author = QAUTHOR;
        VERSION_CONFIG;
    };
};

#include "CfgWeapons.hpp"
""" % ("the base game" if group == "base" else group, required))
        with open(os.path.join(d, "CfgWeapons.hpp"), "w", encoding="utf-8", newline="\n") as f:
            f.write(HEADER + tree.render())
        print("%-32s %4d mode(s)" % (sub, targets[group]))
    if not trees:
        print("every scope in the dump already passes the goggle through - nothing written")


if __name__ == "__main__":
    main()
