FIELDS = ("displayName", "picture", "model", "hiddenSelections", "hiddenSelectionsTextures")


def derapified(pbo, inner, tmp):
    src = os.path.join(WORKSHOP, pbo)
    if not os.path.isfile(src):
        sys.exit("not found: %s - is the mod subscribed?" % src)
    binf, cpp = os.path.join(tmp, "config.bin"), os.path.join(tmp, "config.cpp")
    for f in (binf, cpp):
        if os.path.exists(f):
            os.remove(f)
    subprocess.run(["hemtt", "utils", "pbo", "extract", src, inner, binf], check=True, capture_output=True)
    subprocess.run(["hemtt", "utils", "config", "derapify", binf, cpp], check=True, capture_output=True)
    return open(cpp, encoding="utf-8", errors="replace").read()


def glasses(text):
    """CfgGlasses as {class: (parent, {field: value})} - the derapified text is one property a line."""
    m = re.search(r"(?im)^class CfgGlasses\s*\{", text)
    if not m:
        sys.exit("no CfgGlasses")
    # an array written over several lines is joined back into one property line first
    lines, buf = [], None
    for line in text[m.end():].splitlines():
        s = line.strip()
        if buf is not None:
            buf += " " + s
            if s.startswith("};"):
                lines.append(buf.replace("{ ", "{").replace(" }", "}"))
                buf = None
            continue
        if re.match(r"\w+\[\]\s*=\s*\{$", s):
            buf = s
            continue
        lines.append(s)

    out, depth, cur = {}, 1, None
    for s in lines:
        cm = re.match(r"class (\w+)(?:\s*:\s*(\w+))?\s*\{", s)
        if cm:
            depth += 1
            if depth == 2:
                cur = cm.group(1)
                out[cur] = (cm.group(2), {})
            if s.endswith("};"):
                depth -= 1
            continue
        if re.match(r"class \w+(?:\s*:\s*\w+)?\s*;", s):
            continue
        if s.startswith("}"):
            depth -= 1
            if depth == 0:
                break
            continue
        pm = re.match(r"(\w+)(\[\])?\s*=\s*(.*);$", s)
        if pm and depth == 2 and cur:
            key = next((f for f in FIELDS if f.lower() == pm.group(1).lower()), None)
            if key:
                out[cur][1][key] = pm.group(3)
    return out


def resolve(table, cls):
    vals, seen = {}, set()
    while cls and cls in table and cls not in seen:
        seen.add(cls)
        parent, props = table[cls]
        for k, v in props.items():
            vals.setdefault(k, v)
        cls = parent
    return vals


def strings(value):
    return re.findall(r'"((?:[^"]|"")*)"', value or "")


def item(cls, v):
    name = strings(v.get("displayName"))
    model = strings(v.get("model"))[0]
    sel = ", ".join('"%s"' % s for s in strings(v.get("hiddenSelections")))
    tex = ", ".join('"%s"' % s for s in strings(v.get("hiddenSelectionsTextures")))
    return """    class EGVAR(nvg,{cls}): NVGoggles {{
        author = QAUTHOR;
        scope = 2;
        scopeArsenal = 2;
        displayName = "[JMSB] {name} (AiTR)";
        picture = "{picture}";
        model = "{model}";
        modelOff = "{model}";
        hiddenSelections[] = {{{sel}}};
        hiddenSelectionsTextures[] = {{{tex}}};
        visionMode[] = {{"Normal", "NVG", "TI"}};
        thermalMode[] = {{0, 1}};
        modelOptics = "\\A3\\weapons_f\\reticle\\optics_empty.p3d";
        ACE_nightvision_border = "";
        ACE_nightvision_eyeCups = 0;
        EGVAR(nvg,fullScreen) = 1;
        EGVAR(ecoti,enabled) = 1;
        EGVAR(ecoti,day) = 1;
        class ItemInfo: ItemInfo {{
            uniformModel = "{model}";
            modelOff = "{model}";
            hiddenSelections[] = {{{sel}}};
        }};
    }};
""".format(cls=cls, name=name[0] if name else cls, picture=strings(v.get("picture"))[0], model=model, sel=sel, tex=tex)


def main():
    tmp = tempfile.mkdtemp(prefix="aitr_")
    try:
        for sub, (pbo, inner, patch, classes) in SOURCES.items():
            table = glasses(derapified(pbo, inner, tmp))
            missing = [c for c in classes if c not in table]
            if missing:
                sys.exit("%s has no %s" % (pbo, ", ".join(missing)))
            # its own three files only - XtdGear.hpp beside them is hand-kept (the ACE Arsenal Extended models)
            d = os.path.join(COMPAT, sub)
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, "script_component.hpp"), "w", encoding="utf-8", newline="\n") as f:
                f.write(HEADER + "#define SUBCOMPONENT %s\n#include \"..\\script_component.hpp\"\n" % sub)
            weapons = ",\n".join("            QEGVAR(nvg,%s)" % c for c in classes)
            with open(os.path.join(d, "config.cpp"), "w", encoding="utf-8", newline="\n") as f:
                f.write(HEADER + """#include "script_component.hpp"

// THE AiTR GOGGLES (user, 2026-10-17) - NVG-slot versions of this mod's goggles with night vision, thermal, full
// screen and the ECOTI AiTR boxes in day and NVG mode. See tools/gen_aitr_goggles.py.
class CfgPatches {
    class SUBADDON {
        name = COMPONENT_NAME;
        units[] = {};
        weapons[] = {
%s
        };
        requiredVersion = REQUIRED_VERSION;
        requiredAddons[] = {
            "jmfsb_nvg",
            "jmfsb_ecoti",
            "%s"
        };
        skipWhenMissingDependencies = 1;
        author = QAUTHOR;
        VERSION_CONFIG;
    };
};

#include "CfgWeapons.hpp"
#include "XtdGear.hpp"
""" % (weapons, patch))
            with open(os.path.join(d, "CfgWeapons.hpp"), "w", encoding="utf-8", newline="\n") as f:
                f.write(HEADER + "class CfgWeapons {\n    class Binocular;\n    class NVGoggles: Binocular {\n"
                        "        class ItemInfo;\n    };\n")
                for c in classes:
                    f.write(item(c, resolve(table, c)))
                f.write("};\n")
            print("%-20s %2d goggles" % (sub, len(classes)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
