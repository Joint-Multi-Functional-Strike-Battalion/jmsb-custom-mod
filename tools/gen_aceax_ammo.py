# magazine-name filler, and the MCC donor rounds its class names repeat before FA's own load
FILLER = {"mag", "magazine", "caseless", "cased", "shell", "m855", "125otm", "123hp", "110vmax", "185fmj", "115fmj",
          "103rrlp", "rnd", "rd", "pylonweapon", "deployable", "p"}
CAPACITY = re.compile(r"(?i)^(\d+)(?:rnd|rd)$")


def split_compound(t):
    """StanagTan / PMAGTan: a form with its finish run on; SPS's pmag40rnd: a form with its capacity."""
    m = re.match(r"(?i)^(stanag|pmag|emag)(tan|black|khaki|sand)$", t)
    if m:
        return [m.group(1), m.group(2)]
    m = re.match(r"(?i)^(pmag)(\d+rnd)$", t)
    return [m.group(1), m.group(2)] if m else [t]


def nice_label(stem):
    """[JMSB] <rounds> <calibre> <load> (<magazine>) from a family's stem tokens."""
    toks = [p for t in stem for p in split_compound(t)]
    low = [t.lower() for t in toks]
    jmfsb = bool(low) and low[0] == "fa"
    if not jmfsb or PYRO.search("_".join(low)):
        # base game, ACE and the pyrotechnics: their own words, the engine's filler dropped
        words = [t for t in toks if t.lower() not in ("f",)]
        return " ".join(words), (None, None)
    cap = cal = None
    forms, load, source, side = [], [], None, None
    nums = []
    for t, lt in zip(toks, low):
        m = CAPACITY.match(t)
        if m and cap is None:
            cap = "%sRnd" % m.group(1)
            continue
        if lt in SOURCE_TOKENS:
            source = source or SOURCE_TAG.get(lt)
            side = side or SIDE_TAG.get(lt)
            continue
        if lt in CALIBRE:
            cal = cal or CALIBRE[lt]
            continue
        if lt in FORMS:
            if FORMS[lt] not in forms:
                forms.append(FORMS[lt])
            continue
        if lt in FILLER or lt in FINISHES:
            continue
        if re.match(r"^\d{2,3}$", t):
            nums.append(t)          # MCC writes the capacity as a bare number
            continue
        if t not in load:
            load.append(t)
    if cap is None and nums:
        cap = "%sRnd" % nums[0]
    head = " ".join(x for x in ("[JMSB]", cap, cal, " ".join(load)) if x)
    return head + (" (%s)" % ", ".join(forms) if forms else ""), (source, side)


def slug(stem_key):
    s = re.sub(r"[^A-Za-z0-9]+", "_", stem_key).strip("_").lower()
    return "jmfsb_ammo_" + s


# EVERY MAGAZINE THE MOD DEFINES, not only the mission's list. The list was last touched on 2026-08-29 and knew
# nothing of the tier magazines, the RF/EF/Aegis rounds or anything ported since, so those sat in the panel as raw
# rows beside the folded ones (user, 2026-10-06: "some grouped, some not"). Read from every addon's CfgMagazines,
# less the FA sources whose mods left (gen_fa_tiers.py's DEAD) and the vehicle-only rounds no arsenal lists.
ADDONS = os.path.join(REPO, "addons")
# fa_sps is back in (user, 2026-10-21): SPS Weapons is in the load order again and its
# PMAG 40 / Surefire 60 families need their ACEAX rows.
SKIP_ADDONS = {"fa_rhs", "fa_jca", "fa_jca_mk153", "fa_antidrone_rhs", "fa_antidrone_jca",
               "fa_maincaliber", "fa_mediumcaliber", "fa_vehicles", "fa_missiles", "vehicle"}
# the weapon packs that left the load order: their magazines are still named in the mission's list
GONE_MODS = re.compile(r"(?i)^(?:FA_)?JCA_")
# the parent may be a macro - EGVAR(weapons,60Rnd_545x39_Mag_F) - so anything up to the brace
TOP_CLASS = re.compile(r"(?m)^    class (\w+)\s*(?::\s*[^{;\n]+)?\{")


def mod_mags():
    out = set()
    for root, _dirs, files in os.walk(ADDONS):
        if os.path.relpath(root, ADDONS).split(os.sep)[0] in SKIP_ADDONS:
            continue
        for f in files:
            if not f.lower().endswith(".hpp"):
                continue
            txt = io.open(os.path.join(root, f), encoding="utf-8", errors="replace").read()
            i = txt.find("class CfgMagazines")
            if i >= 0:
                # top-level classes with a body - an external declaration (`class X;`) defines nothing
                out |= set(TOP_CLASS.findall(txt[i:]))
    return out


def read_mags():
    mags = mod_mags()
    if os.path.exists(MAGS):
        txt = io.open(MAGS, encoding="utf-8", errors="replace").read()
        # only the magazines[] array, not the surrounding prose
        mags |= set(re.findall(r'"([A-Za-z0-9_]+)"', txt))
    else:
        sys.stderr.write("!! not found, the mod's own magazines only: %s\n" % MAGS)
    mags = {m for m in mags if not GONE_MODS.search(m)}
    # the weapons the user removed from jmfsb (2026-10-06) - the M32's 6-round 40mm, the Gepard's 9x21, the MP7's
    # 4.6x30, the FAMAS's 5.56 and the XM25's 25mm - which the mission's list still names
    return sorted(m for m in mags if not GONE.search(m))


def crlf(path, lines):
    with io.open(path, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write("\n".join(lines).rstrip("\n") + "\n")


def build(mags):
    """{stem key: (label, {member: vals}, {axis: {key: label}})} for every
    family worth a row - more than one member, differing on some axis."""
    fam = defaultdict(dict)
    stems = {}
    for m in mags:
        stem, vals = classify(m)
        key = "_".join(stem).lower()
        fam[key][m] = vals
        stems.setdefault(key, stem)
    labels = unique_labels(stems)

    groups = {}
    for key, members in fam.items():
        live = OrderedDict()
        for axis in AXES:
            seen = OrderedDict()
            for m, vals in members.items():
                k, label = vals.get(axis, DEFAULT[axis])
                # the plain smoke is white smoke, and says so
                if axis == "colour" and k == "default" and re.search(r"smoke", key):
                    k, label = "white", "White"
                seen[k] = label
            if len(seen) > 1:
                # the plain one first, then the vocabulary's own order, so the
                # buttons read Ball / Red / Green ... on every magazine alike
                order = [DEFAULT[axis][0], "white", "tracer"] + [v[0] for v in COLOURS.values()] + \
                    [v[0] for v in FINISHES.values()] + [v[0] for v in TIERS.values()]
                live[axis] = OrderedDict(sorted(seen.items(), key=lambda kv: order.index(kv[0]) if kv[0] in order else 999))
        # a family with no axis - a lone magazine, or twins that differ in nothing we read - still gets its row
        # name; the runtime renames the row and draws no option panel for it
        groups[key] = (labels[key], members, live)
    return groups


def unique_labels(stems):
    """{stem key: row name}, no two alike. Two families that name the same is the "lots of same name" the
    user saw: first the source tells them apart ([RF], [Aegis] ...), then whatever is left of the class
    name that the other does not have."""
    out, src, side = {}, {}, {}
    for key, stem in stems.items():
        out[key], (src[key], side[key]) = nice_label(stem)
    for _round in range(3):
        by = defaultdict(list)
        for key, lab in out.items():
            by[lab].append(key)
        for lab, keys in by.items():
            if len(keys) < 2:
                continue
            for key in keys:
                if _round == 0:
                    # a mod's round beside FA's own: the mod's is tagged, FA's keeps the plain name
                    if src[key] and len({src[k] for k in keys}) > 1:
                        out[key] = "%s [%s]" % (lab, src[key])
                elif _round == 1:
                    # FA's BLUFOR / OPFOR / INDEP builds of one round
                    if side[key] and len({side[k] for k in keys}) > 1:
                        out[key] = "%s [%s]" % (lab, side[key])
                else:
                    others = set(t.lower() for k in keys if k != key for t in stems[k])
                    extra = [t for t in stems[key] if t.lower() not in others]
                    if extra:
                        out[key] = "%s - %s" % (lab, " ".join(extra))
    return out


def value_of(vals, axis, key):
    k, _label = vals.get(axis, DEFAULT[axis])
    if axis == "colour" and k == "default" and re.search(r"smoke", key):
        k = "white"
    return k


def main():
    mags = read_mags()
    if not mags:
        return 2
    groups = build(mags)

    if "--report" in sys.argv:
        for key in sorted(groups):
            label, members, live = groups[key]
            axes = ", ".join("%s: %s" % (a, "/".join(seen.values())) for a, seen in live.items())
            print("%s  [%d]  %s" % (label, len(members), axes))
            for m in sorted(members):
                print("    %s" % m)
        return 0

    # ---- XtdGearModels: one class per family, its axes and their values ----
    L = [HDR.rstrip("\n"),
         "// One class per family - one round type in one magazine form. `options[]`",
         "// names the axes that family varies on; each axis class lists its",
         "// values. This is ACEAX's schema - see the header of",
         "// tools/gen_aceax_ammo.py for why we use it for magazines, which ACEAX",
         "// itself does not know about.",
         "",
         "class XtdGearModels {",
         "    class CfgMagazines {"]
    for key in sorted(groups):
        label, members, live = groups[key]
        L += ["        class %s {" % slug(key),
              '            label = "%s";' % label]
        if label.startswith("[JMSB]"):
            # the arsenal row's name (fnc_collapsePanel); other sources keep their own displayName
            L += ['            rowName = "%s";' % label]
        L += ["            options[] = {%s};" % ", ".join('"%s"' % a for a in live),
              ""]
        for axis, seen in live.items():
            L += ["            class %s {" % axis,
                  '                label = "%s";' % AXES[axis],
                  "                values[] = {%s};" % ", ".join('"%s"' % k for k in seen),
                  ""]
            for k, lab in seen.items():
                # HEMTT 1.22 (L-C19) wants a known class name in its standard casing; config lookups ignore case,
                # so `class Default` still answers ACEAX's "default" value
                cls = STD_CASE.get(k, k)
                L += ["                class %s { label = \"%s\"; };" % (cls, lab)]
            L += ["            };"]
        L += ["        };"]
    L += ["    };", "};"]
    crlf(os.path.join(ADDON, "XtdGearModels.hpp"), L)

    # ---- XtdGearInfos: every magazine, its family and where it sits ----
    L = [HDR.rstrip("\n"),
         "// Every magazine that belongs to a family, naming the family and its",
         "// value on each of that family's axes. A magazine not listed here is",
         "// left alone and keeps its own row.",
         "",
         "class XtdGearInfos {",
         "    class CfgMagazines {"]
    listed = 0
    for key in sorted(groups):
        label, members, live = groups[key]
        for m in sorted(members):
            vals = members[m]
            parts = ['            model = "%s";' % slug(key)]
            for axis in live:
                parts.append('            %s = "%s";' % (axis, value_of(vals, axis, key)))
            L += ["        class %s {" % m] + parts + ["        };"]
            listed += 1
    L += ["    };", "};"]
    crlf(os.path.join(ADDON, "XtdGearInfos.hpp"), L)

    saved = listed - len(groups)
    print("wrote  addons/aceax_ammo: %d families over %d magazines" % (len(groups), listed))
    print("       arsenal rows: %d -> %d  (%d fewer)" % (len(mags), len(mags) - saved, saved))
    axis_count = defaultdict(int)
    for _k, (_l, _m, live) in groups.items():
        for a in live:
            axis_count[a] += 1
    print("       families by axis: %s"
          % ", ".join("%s %d" % (a, n) for a, n in sorted(axis_count.items())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
