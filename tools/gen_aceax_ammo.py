#!/usr/bin/env python
"""Generate addons/aceax_ammo's XtdGear data from the mission's magazine list.

THE ARSENAL'S AMMO PANEL, COLLAPSED - BY ROUND TYPE (user, 2026-08-29: "the
ammo should be by type like 328 or 329 etc"). The mission arsenal lists over a
thousand magazines. One row per ROUND TYPE in one MAGAZINE FORM - "100Rnd 6.5mm
Mk328", "30Rnd 5.56 Mk332 AP", "30Rnd 6.5mm Mk329 (MSBS)" - and under it, in
the option panel, the things that do not change what the round does:

    tracer   Ball / Red / Green / Yellow / White / Blue / Orange / IR / Dim
    finish   Default / Black / Khaki / Tan / Sand / Coyote / Green ...
    colour   for smoke, flares and chemlights - their colour IS the variant

Calibre, capacity, magazine model (PMAG, EMAG, MSBS, Box) and the load
(Mk328 vs Mk329 vs Mk331 AP vs XM892) each keep their own row: those are what
the player is choosing between on purpose.

THE FIRST VERSION PEELED SUFFIXES and the names do not nest that way: the
finish sits BEFORE the tracer marker ("..._Mk328_Black_T_Red"), the FA tracer
marker is "_T_<Colour>" with the ball round carrying nothing, and the smoke
and flare colours are CamelCase compounds ("SmokeShellBlue", "FlareCIR"). So
one round type came out as four rows - "Mk328", "Mk328 T", "Mk328 Black T",
"Mk328 Khaki T" - and the ball round was never in the family at all. This
version TOKENISES the class name instead: every token is either a tracer
marker, a finish, a colour, or part of the stem, and the stem is the family.

This writes the DATA in ACE Arsenal Extended's XtdGearModels / XtdGearInfos
schema; the runtime that reads it lives in addons/aceax_ammo/functions (ACEAX
itself has no magazine kind). Display names are NOT baked in - the runtime
reads them from config, because several of these magazines come from CDLCs
whose configs are encrypted.

Re-run after changing the mission's magazine list:
    python tools/gen_aceax_ammo.py            # writes the two .hpp
    python tools/gen_aceax_ammo.py --report   # prints every family and its members
"""

