def cls(role):
    return "%s_%s" % (FAC, role)


def vinfo(v):
    """(role, parent, name, crew, paint-or-None) from a VEHICLES entry."""
    role, parent, disp, crew = v[:4]
    return role, parent, disp, crew, (v[4] if len(v) > 4 else None)


def arr(xs):
    return "{" + ",".join('"%s"' % x for x in xs) + "}"


def arr_mixed(xs):
    """Strings quoted, numbers bare - textureList and animationList alternate."""
    return "{" + ",".join('"%s"' % x if isinstance(x, str) else str(x) for x in xs) + "}"


def crlf(name, lines):
    io.open(os.path.join(ADDON, name), "w", encoding="utf-8", newline="\r\n").write("\n".join(lines) + "\n")


def position(i):
    """The wedge every generated faction uses: leader at the point, the rest
    alternating left and right, five metres back each row."""
    if i == 0:
        return "{0,0,0}"
    row = (i + 1) // 2 * 5
    return "{%d,-%d,0}" % (row if i % 2 else -row, row)


def tier_mags(mags, famap, tiered):
    out, hit = [], 0
    for m in mags:
        fa = famap.get(m) or ATLAS_MAG_FA.get(m)
        if fa and fa in tiered:
            out.append("%s_t%d" % (fa, TIER))
            hit += 1
        else:
            out.append(m)
    return out, hit


